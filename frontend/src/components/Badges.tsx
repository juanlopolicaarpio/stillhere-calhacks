export function VisibilityBadge({ visibility }: { visibility: VisibilityLevel }) {
  const copy = visibilityCopy[visibility] ?? {
    label: visibility,
    className: 'border-stone-300/60 bg-stone-50 text-stone-700',
  };
  return (
    <span
      className={`inline-flex items-center rounded-full border px-2.5 py-0.5 text-xs font-medium ${copy.className}`}
    >
      {copy.label}
    </span>
  );
}

export function ReasoningModeBadge({ mode }: { mode: ReasoningMode }) {
  const isClaude = mode === 'claude';
  return (
    <span
      title={
        isClaude
          ? 'This reply was generated by Claude.'
          : 'Claude was unavailable; a non-AI fallback produced this reply.'
      }
      className={`inline-flex items-center gap-1 rounded-full border px-2.5 py-0.5 text-xs font-medium ${
        isClaude
          ? 'border-violet-300/60 bg-violet-50 text-violet-700 dark:border-violet-300/30 dark:bg-violet-500/10 dark:text-violet-200'
          : 'border-stone-300/60 bg-stone-100 text-stone-700 dark:border-stone-300/30 dark:bg-stone-500/10 dark:text-stone-200'
      }`}
    >
      {isClaude ? 'Claude reasoning' : 'Fallback reasoning'}
    </span>
  );
}
